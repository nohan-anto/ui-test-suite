/** Render and parse test-cases.md. The Markdown is the source of truth so hand edits carry into the test phase. */
import { TestCaseSchema, type TestCase } from "../phases/protocol.ts";

export interface TestCasesDoc {
  ticket: string;
  title: string;
  summary: string;
  cases: TestCase[];
}

const NONE = "_none_";
const SECTIONS: [keyof TestCase, string][] = [
  ["preconditions", "Preconditions"],
  ["testData", "Test data"],
  ["steps", "Steps"],
  ["expected", "Expected result"],
];

export function renderTestCases(doc: TestCasesDoc): string {
  const out = [
    `# Test cases: ${doc.ticket} — ${doc.title}`,
    "",
    `> Generated by uitest on ${new Date().toISOString().slice(0, 16).replace("T", " ")}. You can edit this file before running \`uitest test\`.`,
    "> Keep the \`## TC-NNN: title\` headings and the bold field labels. Tag a case \`destructive\` to require confirmation before it runs.",
    "",
  ];
  if (doc.summary) out.push("## Summary", "", doc.summary, "");
  for (const c of doc.cases) {
    out.push(
      `## ${c.id}: ${c.title}`,
      "",
      `- **Priority:** ${c.priority}`,
      `- **Traces to:** ${c.tracesTo.join(", ") || NONE}`,
      `- **Tags:** ${c.tags.join(", ") || NONE}`,
      "",
    );
    for (const [key, label] of SECTIONS) {
      const items = c[key] as string[];
      out.push(`**${label}**`, "");
      if (!items.length) out.push(`- ${NONE}`);
      else items.forEach((s, i) => out.push(key === "steps" ? `${i + 1}. ${s}` : `- ${s}`));
      out.push("");
    }
  }
  return out.join("\n");
}

function splitList(v: string): string[] {
  const t = v.trim();
  return !t || t === NONE ? [] : t.split(",").map((s) => s.trim()).filter(Boolean);
}

export function parseTestCases(md: string): TestCasesDoc {
  const header = md.match(/^# Test cases:\s*(\S+)\s*—\s*(.*)$/m);
  const summary = md.match(/^## Summary\s*\n([\s\S]*?)(?=^## )/m)?.[1]?.trim() ?? "";
  const blocks = md.split(/^(?=## TC-\d{3,}:)/m).slice(1);
  const cases: TestCase[] = [];
  const errors: string[] = [];

  for (const block of blocks) {
    const head = block.match(/^## (TC-\d{3,}):\s*(.*)$/m)!;
    const field = (label: string) => block.match(new RegExp(`^- \\*\\*${label}:\\*\\*\\s*(.*)$`, "m"))?.[1] ?? "";
    const section = (label: string): string[] => {
      const m = block.match(new RegExp(`^\\*\\*${label}\\*\\*\\s*\\n([\\s\\S]*?)(?=^\\*\\*[^*]+\\*\\*\\s*$|(?![\\s\\S]))`, "m"));
      if (!m) return [];
      return m[1]!
        .split("\n")
        .map((l) => l.match(/^\s*(?:[-*]|\d+[.)])\s+(.*)$/)?.[1]?.trim())
        .filter((l): l is string => !!l && l !== NONE);
    };
    const candidate = {
      id: head[1],
      title: head[2]!.trim(),
      priority: field("Priority").trim() || "P2",
      tracesTo: splitList(field("Traces to")),
      tags: splitList(field("Tags")),
      preconditions: section("Preconditions"),
      testData: section("Test data"),
      steps: section("Steps"),
      expected: section("Expected result"),
    };
    const r = TestCaseSchema.safeParse(candidate);
    if (r.success) cases.push(r.data);
    else errors.push(`${head[1]}: ${r.error.issues.map((i) => `${i.path.join(".")} ${i.message}`).join("; ")}`);
  }
  if (errors.length) throw new Error(`test-cases.md has invalid cases:\n  ${errors.join("\n  ")}`);
  return { ticket: header?.[1] ?? "", title: header?.[2]?.trim() ?? "", summary, cases };
}
